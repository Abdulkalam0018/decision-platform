"""Generate docs/DECISION_EXAMPLES.md from real executions.

Every example below is produced by running the actual engine against the
shipped configuration (fixed clock, temporary database), so the document can
never drift from the code. Re-run with:  python scripts/generate_examples.py
"""

from __future__ import annotations

import json
import random
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import yaml  # noqa: E402

from decision_platform.domain.clock import FixedClock  # noqa: E402
from decision_platform.persistence.db import Database  # noqa: E402
from decision_platform.service import DecisionService, InputValidationError  # noqa: E402

EX = ROOT / "examples" / "requests"
OUT = ROOT / "docs" / "DECISION_EXAMPLES.md"


def j(data: Any) -> str:
    return "```json\n" + json.dumps(data, indent=2, default=str) + "\n```"


def load(name: str) -> dict[str, Any]:
    return json.loads((EX / name).read_text())


def rules_table(exp: dict[str, Any]) -> str:
    if not exp["rules_triggered"]:
        return "_No rule failed._ Passed: " + ", ".join(f"`{r}`" for r in exp["rules_passed"]) + "\n"
    lines = ["| Rule | Outcome | Action | Reason | Data referenced |", "|---|---|---|---|---|"]
    for r in exp["rules_triggered"]:
        refs = "<br>".join(f"`{k}` = `{v}`" for k, v in r["data_refs"].items())
        lines.append(f"| `{r['rule_id']}` {r['name']} | {r['outcome']} | {r['action']} | {r['reason']} | {refs} |")
    return "\n".join(lines) + "\n"


def lifecycle(exp: dict[str, Any]) -> str:
    return " -> ".join(t["to_status"] for t in exp["lifecycle"])


def section(title: str, intro: str, payload: Any, svc: DecisionService, rid: str, extra: str = "") -> str:
    exp = svc.explain(rid)
    audit = [f"{e['seq']:>3} {e['event_type']:<24} {e['actor']}" for e in svc.audit(rid)]
    return f"""
## {title}

{intro}

**Input** (`{exp["workflow"]}` v{exp["workflow_version"]})

{j(payload)}

**Path taken:** {" -> ".join(f"{p['stage']}[{p['outcome']}]" for p in exp["path"])}

**Rules triggered**

{rules_table(exp)}
**Output**

{j(exp["decision"])}

**Lifecycle:** {lifecycle(exp)}

**Audit reasoning (plain-language explanation generated from the stored trace)**

```text
{exp["narrative"]}
```

<details><summary>Audit events for this request (hash-chained)</summary>

```text
{chr(10).join(audit)}
```
</details>
{extra}
"""


def main() -> None:
    tmp = tempfile.mkdtemp()
    clock = FixedClock()
    db = Database(Path(tmp) / "examples.db")
    svc = DecisionService(db, clock=clock, sleep=lambda s: None, rng=random.Random(7))
    svc.load_workflows(ROOT / "config" / "workflows")
    parts: list[str] = []

    parts.append("""# Decision explanation examples

Generated by `scripts/generate_examples.py` from real runs of the engine against the
shipped configuration (fixed clock: 2026-11-13 09:00 UTC). Each example shows the
**input**, the **rules triggered** with the exact **data referenced**, the **output**
decision and the **audit reasoning**. Request ids are random UUIDs.

| # | Scenario | Outcome |
|---|---|---|
""")
    index: list[tuple[str, str]] = []

    # 1 approved
    p = load("loan_approve.json")
    r = svc.submit("loan_application", p, "ex-approve").body
    index.append(("Loan approved (happy path)", r["status"]))
    parts.append(
        section(
            "1. Loan approved (happy path)",
            "Clean applicant: every rule passes, both external checks succeed first time, "
            "routing takes the default branch.",
            p,
            svc,
            r["request_id"],
        )
    )

    # 2 multi-reason reject
    p = load("loan_reject_eligibility.json")
    r = svc.submit("loan_application", p, "ex-reject-elig").body
    index.append(("Loan rejected for two reasons at eligibility", r["status"]))
    parts.append(
        section(
            "2. Loan rejected, all failing rules reported",
            "Minor requesting more than the product limit. The rule stage collects every failure "
            "(DMN 'collect' policy) so the explanation lists both reasons, and no external call is made.",
            p,
            svc,
            r["request_id"],
        )
    )

    # 3 bureau reject
    p = load("loan_reject_credit.json")
    r = svc.submit("loan_application", p, "ex-reject-credit").body
    index.append(("Loan rejected on bureau data (reject beats review)", r["status"]))
    parts.append(
        section(
            "3. Loan rejected on credit bureau data",
            "Two risk rules fail: one with action `review`, one with `reject`. The most severe action wins.",
            p,
            svc,
            r["request_id"],
        )
    )

    # 4 flag
    p = load("loan_flagged.json")
    r = svc.submit("loan_application", p, "ex-flag").body
    index.append(("Loan approved with a non-blocking flag", r["status"]))
    parts.append(
        section(
            "4. Approved with a non-blocking flag",
            "Score 634 passes the 620 minimum but is below the 680 prime band. Rule RISK-006 has action `flag`: "
            "it is recorded in the decision but does not change the outcome.",
            p,
            svc,
            r["request_id"],
        )
    )

    # 5 manual review + reviewer
    p = load("loan_manual_review.json")
    r = svc.submit("loan_application", p, "ex-review").body
    rid = r["request_id"]
    svc.review(
        rid, "approve", "underwriter.kim", "Verified salary slips; existing debt is a car loan ending in 3 months"
    )
    index.append(("Conditional branch to manual review, then reviewer approves", "MANUAL_REVIEW -> APPROVED"))
    parts.append(
        section(
            "5. Conditional branching to manual review, resolved by a reviewer",
            "All risk rules pass but the debt-to-income ratio (0.4167) is above the review threshold (0.36), "
            "so the routing branch sends it to manual review. An underwriter then approves with a justification. "
            "The decision keeps the engine's recommendation alongside the human override.",
            p,
            svc,
            rid,
        )
    )

    # 6 dependency failure + retry
    p = load("loan_approve.json") | {"applicant": load("loan_approve.json")["applicant"] | {"id": "APP-1003"}}
    svc.hub.get("credit_bureau").configure(fail_next=["transient", "timeout", "transient"])
    r = svc.submit("loan_application", p, "ex-retry").body
    parked_status = r["status"]
    clock.advance(16 * 60)
    tick = svc.process_due_retries()
    rid = r["request_id"]
    attempts = [
        run["trace"].get("attempts") for run in svc.history(rid)["stage_runs"] if run["stage_id"] == "credit_check"
    ]
    index.append(
        ("Dependency outage: inline retries, parked, resumed by worker", f"{parked_status} -> {svc.get(rid)['status']}")
    )
    parts.append(
        section(
            "6. External dependency failure, retry and resume",
            "The credit bureau fails three times (503, timeout, 503). Inline retries with full-jitter backoff are "
            "exhausted, so the request is parked in `RETRY_PENDING` with a scheduled retry instead of failing. "
            "The retry worker later resumes it **from the failed stage** "
            "(eligibility and affordability are not re-run).",
            p,
            svc,
            rid,
            extra="\n**Dependency attempts per execution of `credit_check`**\n\n"
            + j(attempts)
            + "\n\n**Worker tick result**\n\n"
            + j(tick),
        )
    )

    # 7 duplicates
    p = load("loan_approve.json")
    bureau_before = svc.hub.get("credit_bureau").side_effects
    first = svc.submit("loan_application", p, "ex-approve")
    dup = svc.submit("loan_application", p, "client-generated-new-key")
    try:
        svc.submit("loan_application", p | {"loan": p["loan"] | {"amount": 1}}, "ex-approve")
        conflict = None
    except Exception as exc:  # IdempotencyKeyReuse
        conflict = {"error": type(exc).__name__, "detail": str(exc)}
    bureau_after = svc.hub.get("credit_bureau").side_effects
    total_requests = db.read().execute("SELECT COUNT(*) c FROM requests").fetchone()["c"]
    index.append(("Duplicate submissions (idempotency + business duplicate)", "replayed, no new request"))
    parts.append(f"""
## 7. Duplicate requests

Three duplicate cases against example 1:

1. **Same `Idempotency-Key`, same payload** (client retry after a timeout): the original request is returned with
   `Idempotent-Replayed: true`. No new request, no second bureau call.
2. **New key, same business key** (`applicant.id + loan.purpose + loan.amount` within 24h): detected as a business
   duplicate and the existing decision is returned with `Duplicate-Of`.
3. **Same key, different payload**: refused (HTTP 422), per the IETF Idempotency-Key draft.

Replay (case 1): HTTP {first.http_status}, replayed={first.replayed}

{j({k: first.body[k] for k in ("request_id", "status")})}

Business duplicate (case 2): HTTP {dup.http_status}, duplicate_of=`{dup.duplicate_of}`

Key reuse with a different payload (case 3):

{j(conflict)}

Credit bureau executions before these three submissions: {bureau_before}; after: {bureau_after} (unchanged).
Requests stored in total at this point: {total_requests} (no row was added by any of the three).
""")

    # 8 invalid input
    p = load("loan_invalid.json")
    try:
        svc.submit("loan_application", p, "ex-invalid")
        errors: Any = None
    except InputValidationError as exc:
        errors = exc.details["errors"]
    index.append(("Invalid input rejected at intake", "HTTP 422"))
    parts.append(f"""
## 8. Invalid input

The payload is checked against the workflow's JSON Schema before anything is persisted.
All violations are returned at once (HTTP 422, `application/problem+json`). The audit log
records an `intake.rejected` event with the payload's SHA-256, not the raw personal data.

**Input**

{j(p)}

**Errors returned**

{j(errors)}
""")

    # 9 rule change
    candidate = yaml.safe_load((ROOT / "config" / "candidates" / "loan_application.v2.yaml").read_text())
    svc.registry.register(candidate, actor="risk-team", activate=False)
    report = svc.impact("loan_application", 1, 2)
    svc.registry.activate("loan_application", 2, actor="risk-team", reason="tighten credit policy (CRP-2026-11)")
    p = load("loan_flagged.json") | {"loan": load("loan_flagged.json")["loan"] | {"amount": 640000}}
    r = svc.submit("loan_application", p, "ex-v2").body
    index.append(("Rule change: v2 activated without code change", "same profile APPROVED on v1, REJECTED on v2"))
    parts.append(
        section(
            "9. Rule change without code change (v1 -> v2)",
            "`loan_application` v2 raises the minimum score 620 -> 650, lowers max DTI 0.45 -> 0.40 and adds "
            "rule RISK-007. Before activation the impact report replays every v1 decision against v2 using the "
            "recorded bureau responses (no live calls). After activation, the same credit profile as example 4 "
            "is rejected, while example 4 itself remains APPROVED under v1 forever (version pinning).",
            p,
            svc,
            r["request_id"],
            extra="\n**Impact report produced before activation** "
            "(`GET /v1/workflows/loan_application/impact?from_version=1&to_version=2`)\n\n"
            + j(report)
            + "\n\n**Activation history**\n\n"
            + j(svc.registry.activation_history("loan_application")),
        )
    )

    # 10 claim
    p = load("claim_approve.json")
    r = svc.submit("insurance_claim", p, "ex-claim").body
    index.append(("Insurance claim approved with computed payout", r["status"]))
    parts.append(
        section(
            "10. Insurance claim approved with computed payout",
            "Policy looked up from the policy service, payout derived as min(claimed, limit) - deductible, "
            "documents verified, payout under the auto-approve limit.",
            p,
            svc,
            r["request_id"],
        )
    )

    p = load("claim_theft_no_report.json")
    r = svc.submit("insurance_claim", p, "ex-claim-theft").body
    index.append(("Theft claim without police report (conditional rule)", r["status"]))
    parts.append(
        section(
            "11. Conditional rule: theft claim without a police report",
            "CLM-003 only applies when `incident.type == 'theft'`; "
            "for other claim types it is reported as not applicable.",
            p,
            svc,
            r["request_id"],
        )
    )

    p = load("vendor_sanctioned.json")
    r = svc.submit("vendor_approval", p, "ex-vendor").body
    index.append(("Vendor rejected by sanctions screening", r["status"]))
    parts.append(
        section(
            "12. Vendor rejected by sanctions screening",
            "Sanctions rule stage uses `evaluation: first_failure`; the vendor name matches a list.",
            p,
            svc,
            r["request_id"],
        )
    )

    # 13 audit tamper
    ok_before = svc.verify_audit()
    conn = db.read()
    victim = conn.execute("SELECT id FROM requests WHERE status='REJECTED' LIMIT 1").fetchone()["id"]
    saved = conn.execute("SELECT status, decision FROM requests WHERE id=?", (victim,)).fetchone()
    conn.execute(
        "UPDATE requests SET status='APPROVED', decision=replace(decision,'REJECTED','APPROVED') WHERE id=?", (victim,)
    )
    forged_row = svc.verify_audit()
    conn.execute("UPDATE requests SET status=?, decision=? WHERE id=?", (saved["status"], saved["decision"], victim))
    seq = conn.execute("SELECT seq FROM audit_events WHERE event_type='decision.made' ORDER BY seq LIMIT 1").fetchone()[
        "seq"
    ]
    conn.execute("UPDATE audit_events SET payload=replace(payload,'APPROVED','REJECTED') WHERE seq=?", (seq,))
    tampered = svc.verify_audit()
    index.append(("Audit log tamper detection", "detected"))
    parts.append(f"""
## 13. Tamper-evident audit log

Every audit event stores `hash = SHA-256(prev_hash || event)`. Editing any historical row breaks the chain, and
verification also cross-checks every request's stored status and decision against the last audited ones.

Before tampering (`GET /v1/admin/audit/verify`):

{j(ok_before)}

**Attack 1:** flip a REJECTED request to APPROVED directly in the `requests` table (audit rows untouched).
The chain is intact, but the state cross-check catches the forged outcome:

{j(forged_row)}

**Attack 2:** edit the outcome inside a stored `decision.made` audit event. The chain breaks at that row:

{j(tampered)}

Limitation: rewriting the entire chain consistently is only detectable by anchoring `head_hash` outside the
database (see SCALING.md).
""")

    header = parts[0] + "\n".join(f"| {i} | {t} | {o} |" for i, (t, o) in enumerate(index, 1)) + "\n"
    OUT.write_text(header + "".join(parts[1:]))
    db.close()
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
